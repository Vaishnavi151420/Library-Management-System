    private void loadProfile() {

    try {

        Connection con = Connect.Connection();

        String sql =
                "SELECT id, name, course, branch, semester " +
                "FROM student " +
                "WHERE id = ?";

        PreparedStatement pat = con.prepareStatement(sql);

        pat.setString(1, String.valueOf(studentId));

        ResultSet rs = pat.executeQuery();

        if (rs.next()) {

            txtid.setText(rs.getString("id"));
            txtname.setText(rs.getString("name"));
            txtcourse.setText(rs.getString("course"));
            txtbranch.setText(rs.getString("branch"));
            txtsem.setText(rs.getString("semester"));

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "Student profile not found for ID: " + studentId
            );
        }

        rs.close();
        pat.close();
        con.close();

    } catch (SQLException ex) {

        JOptionPane.showMessageDialog(
                this,
                "Error loading profile: "
        );
    }
}
