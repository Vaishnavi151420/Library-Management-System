    private void loadBooks() {

        try {

            Connection con = Connect.Connection();

            String sql
                    = "SELECT id, name, publisher, year, price, status "
                    + "FROM book "
                    + "WHERE status = ?";

            PreparedStatement pat = con.prepareStatement(sql);

            pat.setString(1, "AVAILABLE");

            ResultSet rs = pat.executeQuery();

            DefaultTableModel model
                    = (DefaultTableModel) tableBooks.getModel();

            model.setRowCount(0);

            while (rs.next()) {

                model.addRow(new Object[]{
                    rs.getInt("id"),
                    rs.getString("name"),
                    rs.getString("publisher"),
                    rs.getString("year"),
                    rs.getString("price"),
                    rs.getString("status")
                });
            }

            rs.close();
            pat.close();
            con.close();

        } catch (SQLException ex) {

            JOptionPane.showMessageDialog(
                    this,
                    "Error loading books: " + ex.getMessage()
            );
        }
    }

