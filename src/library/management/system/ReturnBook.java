    private void btnsearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsearchActionPerformed
        if (txtstudentid.getText().equals("")) {
            JOptionPane.showMessageDialog(this, "Please Enter Student id and Search it");
            txtstudentid.requestFocus();
        } else {
            try {
                pat = con.prepareStatement(
                        "SELECT student.name, book.id, book.name, book.issuedate, book.duedate "
                        + "FROM book INNER JOIN student ON book.studentid = student.id "
                        + "WHERE book.studentid = ?"
                );

                pat.setString(1, txtstudentid.getText());

                rs = pat.executeQuery();

                if (rs.next()) {
                    txtstudentname.setText(rs.getString(1));
                    txtbookid.setText(rs.getString(2));
                    txtbookname.setText(rs.getString(3));
                    txtissuedate.setText(rs.getString(4));
                    txtduedate.setText(rs.getString(5));

                } else {
                    JOptionPane.showMessageDialog(this, "Please enter valid student id");
                }
            } catch (SQLException ex) {
                System.getLogger(ReturnBook.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
            }
        }

        // TODO add your handling code here:
    }//GEN-LAST:event_btnsearchActionPerformed

    private void btnreturnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnreturnActionPerformed
        if (txtstudentid.getText().trim().equals("")) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please enter Student ID and search it"
            );

            txtstudentid.requestFocus();
            return;
        }

        if (txtbookid.getText().trim().equals("")) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please search the student first"
            );

            return;
        }

        try {

            pat = con.prepareStatement(
                    "UPDATE book SET status=?, issuedate=NULL, duedate=NULL, studentid=NULL WHERE id=?"
            );

            // Book becomes available
            pat.setString(1, "AVAILABLE");

            // Book ID
            pat.setString(2, txtbookid.getText().trim());

            int updated = pat.executeUpdate();

            if (updated > 0) {

                JOptionPane.showMessageDialog(
                        this,
                        "Book Returned Successfully!"
                );

                // Clear fields
                txtissuedate.setText("");
                txtduedate.setText("");
                txtbookid.setText("");
                txtbookname.setText("");
                txtstudentid.setText("");
                txtstudentname.setText("");

            } else {

                JOptionPane.showMessageDialog(
                        this,
                        "Book was not returned. Please check the Book ID."
                );
            }

        } catch (SQLException ex) {

            JOptionPane.showMessageDialog(
                    this,
                    "Return Book Error: " 
            );

            ex.printStackTrace();
        }

// TODO add your handling code here:
    }//GEN-LAST:event_btnreturnActionPerformed

